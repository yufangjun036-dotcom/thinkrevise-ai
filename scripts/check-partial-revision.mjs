// Offline regressions for the actual screenshot incident and nearby controls.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const source = fs.readFileSync(new URL('../app/api/coach/route.ts', import.meta.url), 'utf8').replace(/^import .*;\n/gm, '')
  + '\nexport { checkedSentenceFeedback, validateLiveResult, addRevisionComparison, preserveOptionalCoordinatorComma, partialRevisionProgress };';
const box = { exports: {} };
new Function('exports', 'require', 'module', ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(box.exports, require, box);
const f = box.exports;
const item = (quote, replacement, category = '语言准确性 · 综合语言修改') => ({ category, quote, correction: `${quote} → ${replacement}`, why: '本句实际修改。', suggestion: '', confidence: '高' });
const result = (feedback, modelRevision = '') => ({ feedback, modelRevision, summary: '', overview: [], meaningRisk: '', provider: 'openai' });
const check = replacement => ({ index: 0, replacement, why: '检查标点与语言形式。', category: '语言准确性 · 句子连接与标点', confidence: '高' });
const original = 'Many students is using AI without checking the answer careful, and teh feedback can be confusing.';
const revised = original.replace('teh', 'the');
const correct = 'Many students are using AI without checking the answer carefully, and the feedback can be confusing.';
const prior = item(original, correct);
const current = item(revised, correct);
const comma = 'It gives a lot of feedback and students can finish work fast.';
const extraComma = comma.replace(' and', ', and');
const commaItem = item(comma, extraComma, '语言准确性 · 句子连接与标点');
const serial = 'Light, temperature and friendships might affect a choice, but the example does not measure those factors.';
const future = 'I would also ask another member to listen before we share the recording.';
assert.equal(f.preserveOptionalCoordinatorComma(future,future.replace('we share','we shared')),future);
assert.equal(f.preserveOptionalCoordinatorComma('We would recommend checking before you start.','We would recommend checking before you started.'),'We would recommend checking before you start.');
assert.equal(f.preserveOptionalCoordinatorComma('Yesterday we share the recording.','Yesterday we shared the recording.'),'Yesterday we shared the recording.');
const currentState = 'We noticed a bridge and a row of shops that no longer exist.';
assert.equal(f.preserveOptionalCoordinatorComma(currentState,currentState.replace('exist.','existed.')),currentState);
assert.equal(f.preserveOptionalCoordinatorComma('We studied a building which no longer exists.','We studied a building which no longer existed.'),'We studied a building which no longer exists.');
assert.equal(f.preserveOptionalCoordinatorComma('The shops no longer exist in 1920.','The shops no longer existed in 1920.'),'The shops no longer existed in 1920.');
const rather = 'That would provide information rather than automatically proving that the method works.';
assert.equal(f.preserveOptionalCoordinatorComma(rather, rather.replace('proving', 'prove')), rather);
assert.equal(f.preserveOptionalCoordinatorComma('We listen rather than guessing.', 'We listen rather than guess.'), 'We listen rather than guessing.');
assert.equal(f.preserveOptionalCoordinatorComma('They are prove the claim.', 'They are proving the claim.'), 'They are proving the claim.');
assert.equal(f.preserveOptionalCoordinatorComma(serial, serial.replace('temperature and', 'temperature, and')), serial);
assert.equal(f.preserveOptionalCoordinatorComma('Rain, wind and snow can delay travel.', 'Rain, wind, and snow can delay travel.'), 'Rain, wind and snow can delay travel.');
assert.equal(f.preserveOptionalCoordinatorComma('Rain, wind, and snow can delay travel.', 'Rain, wind and snow can delay travel.'), 'Rain, wind, and snow can delay travel.');
assert.equal(f.preserveOptionalCoordinatorComma('Rain fell, roads flooded.', 'Rain fell; roads flooded.'), 'Rain fell; roads flooded.');
assert.equal(f.preserveOptionalCoordinatorComma(serial, serial.replace('might', 'will').replace('temperature and', 'temperature, and')), serial.replace('might', 'will').replace('temperature and', 'temperature, and'));

const partial = f.addRevisionComparison(result([current, commaItem]), `${comma} ${revised}`, `${comma} ${original}`, [prior]);
assert.equal(partial.feedback.length, 1, 'Optional punctuation must not become a second-round miss');
assert.equal(partial.feedback[0].revisionStatus, 'partial');
assert.deepEqual(partial.feedback[0].revisionProgress, { completed: ['“teh” → “the”'], pending: ['“is” → “are”', '“careful” → “carefully”'] });
assert.equal(partial.revisionComparison.partialCount, 1);
assert.equal(partial.revisionComparison.changedCount, 0);
assert.equal(partial.revisionComparison.supplementalCount, 0);
assert.equal(partial.revisionComparison.resolved.length, 0, 'The grouped card is not fully resolved');
assert.equal(partial.revisionComparison.initialCount, 1, 'Card count must not masquerade as atomic error count');
const unchanged = f.addRevisionComparison(result([prior]), original, original, [prior]);
assert.equal(unchanged.feedback[0].revisionStatus, 'remaining');
assert.equal(unchanged.feedback[0].revisionProgress, undefined);
const fixed = f.addRevisionComparison(result([]), correct, original, [prior]);
assert.equal(fixed.revisionComparison.resolved.length, 1);
assert.equal(fixed.feedback.length, 0);
const incorrect = original.replace('teh', 'that');
assert.equal(f.partialRevisionProgress(prior, item(incorrect, correct), original, incorrect), undefined, 'Changing a word is not evidence of completing the requested fix');
const deleted = original.replace('teh ', '');
assert.equal(f.partialRevisionProgress(prior, item(deleted, correct), original, deleted), undefined, 'Deleting a required word is not completing the correction');
assert.equal(f.partialRevisionProgress(prior, current, `${original} ${original}`, `${revised} ${original}`), undefined, 'Duplicate sentences must not get guessed progress');
assert.equal(f.partialRevisionProgress(prior, current, `${original} Another sentence follows.`, `Another sentence follows. ${revised}`), undefined, 'Reordered sentences require conservative matching');
assert.equal(f.partialRevisionProgress(prior, item(revised, original), original, revised), undefined, 'Do not credit an edit that this review would reverse');
const addedError = revised.replace('using AI', 'use AI');
const withNewError = f.addRevisionComparison(result([item(addedError, correct)]), addedError, original, [prior]);
assert.equal(withNewError.feedback[0].revisionStatus, 'partial');
assert.deepEqual(withNewError.feedback[0].revisionProgress.completed, ['“teh” → “the”']);
assert.ok(withNewError.feedback[0].revisionProgress.pending.some(text => text.includes('use')));

assert.deepEqual(f.checkedSentenceFeedback([check(extraComma)], [comma]), []);
assert.deepEqual(f.checkedSentenceFeedback([check(comma)], [extraComma]), [], 'Either optional comma choice is retained');
for (const mode of ['coach', 'model', 'rewrite']) {
  const validated = f.validateLiveResult(result([commaItem], extraComma), comma, mode, 0, true, false);
  assert.equal(validated.feedback.length, 0, mode);
  assert.equal(validated.modelRevision, comma, 'Do not silently apply the rejected comma');
}
const mixed = comma.replace('gives', 'give');
const mixedCheck = f.checkedSentenceFeedback([check(extraComma)], [mixed]);
assert.equal(mixedCheck.length, 1);
assert.equal(mixedCheck[0].correction, `${mixed} → ${comma}`);
assert.doesNotMatch(mixedCheck[0].why, /补入“,”/);
const splice = 'It gives feedback, students can learn independently.';
const spliceFix = 'It gives feedback; students can learn independently.';
assert.equal(f.checkedSentenceFeedback([check(spliceFix)], [splice]).length, 1, 'A genuine comma splice remains a language issue');
const possessive = "Students work is valuable.";
assert.equal(f.checkedSentenceFeedback([check("Students’ work is valuable.")], [possessive]).length, 1, 'Possessive punctuation is not optional');
const list = 'We discuss teachers, parents and students.';
assert.equal(f.preserveOptionalCoordinatorComma(list, list.replace(' and', ', and')), list.replace(' and', ', and'), 'Do not infer clause rules for lists');
const complex = 'It gives feedback, which can be useful and students can revise.';
assert.equal(f.preserveOptionalCoordinatorComma(complex, complex.replace(' and', ', and')), complex.replace(' and', ', and'), 'Do not apply this narrow rule inside complex punctuation');
const scope = 'I think she dances and he can sing.';
assert.equal(f.preserveOptionalCoordinatorComma(scope, scope.replace(' and', ', and')), scope.replace(' and', ', and'), 'Commas may change embedded-clause scope');
console.log('Partial-revision incident passed: completed vs pending edits, conservative alignment, optional commas, real punctuation controls and all modes. No AI calls.');
